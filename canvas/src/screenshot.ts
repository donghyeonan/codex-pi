/**
 * canvas_screenshot backend: headless Chrome loads the pi-canvas app in capture mode
 * (`?capture=1&doc=…&node=…`) over the DevTools pipe, so the PNG is exactly what the editor renders, including
 * sandboxed frame iframes that run scripts or load CDN CSS.
 */
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { delimiter, dirname, join } from "node:path";
import type { Readable, Writable } from "node:stream";
import type { CanvasDoc } from "./store.ts";

export const MAX_SIDE = 4096;
const TIMEOUT_MS = 25_000;
/** how long to wait for the capture page's ready flag before shooting anyway */
const READY_MS = 15_000;
/** extra time after ready for script-driven rendering (charts, CSS generated by CDN scripts) */
const SETTLE_MS = 300;
const READY_EXPR = "document.documentElement && document.documentElement.dataset.captureReady === '1' ? (document.documentElement.dataset.captureError || 'ok') : ''";

const MAC_APPS = [
	"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
	"/Applications/Chromium.app/Contents/MacOS/Chromium",
	"/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
	"/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
];
const PATH_NAMES = ["google-chrome", "chromium", "chromium-browser"];

/** PI_CANVAS_CHROME, then well-known macOS apps, then Chrome/Chromium on PATH. */
export function findChrome(): string | undefined {
	const env = process.env.PI_CANVAS_CHROME;
	if (env) return existsSync(env) ? env : undefined;
	if (process.platform === "darwin") for (const p of MAC_APPS) if (existsSync(p)) return p;
	for (const name of PATH_NAMES) {
		for (const dir of (process.env.PATH ?? "").split(delimiter)) {
			const p = dir && join(dir, name);
			if (p && existsSync(p)) return p;
		}
	}
	return undefined;
}

export interface Rect {
	x: number;
	y: number;
	w: number;
	h: number;
}

/** World rect of a node (sum of parent offsets), or the union of all visible top-level layers. */
export function targetRect(doc: CanvasDoc, nodeId?: string): Rect {
	const byId = new Map(doc.nodes.map((n) => [n.id, n]));
	if (nodeId) {
		const n = byId.get(nodeId);
		if (!n) throw new Error(`unknown node id: ${nodeId} (canvas_read lists the node ids of doc ${doc.id})`);
		let x = n.x;
		let y = n.y;
		const seen = new Set([n.id]);
		for (let p = n.parentId ? byId.get(n.parentId) : undefined; p && !seen.has(p.id); p = p.parentId ? byId.get(p.parentId) : undefined) {
			seen.add(p.id);
			x += p.x;
			y += p.y;
		}
		return { x, y, w: n.w, h: n.h };
	}
	const tops = doc.nodes.filter((n) => (!n.parentId || !byId.has(n.parentId)) && n.visible !== false);
	if (!tops.length) throw new Error(`document ${doc.id} has no visible layers to screenshot`);
	const x1 = Math.min(...tops.map((n) => n.x));
	const y1 = Math.min(...tops.map((n) => n.y));
	const x2 = Math.max(...tops.map((n) => n.x + n.w));
	const y2 = Math.max(...tops.map((n) => n.y + n.h));
	return { x: x1, y: y1, w: x2 - x1, h: y2 - y1 };
}

export function pngSize(buf: Buffer): { width: number; height: number } {
	return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

export interface ShotResult {
	png: Buffer;
	width: number;
	height: number;
	/** device scale factor actually used (lower than requested when capped at MAX_SIDE) */
	scale: number;
	capped: boolean;
	/** false when the page never signalled ready (slow CDN/iframe); the shot was taken anyway */
	complete: boolean;
}

/**
 * Run headless Chrome over the DevTools pipe (no WebSocket, no dependencies): open `url` with a
 * W×H CSS-pixel viewport, wait for the capture page to set data-capture-ready (frame iframes,
 * images, CDN scripts and fonts loaded), then write a PNG to `out`. Hard timeout 25s.
 */
export async function captureScreenshot(opts: { chrome: string; url: string; width: number; height: number; scale: number; out: string; signal?: AbortSignal }): Promise<ShotResult> {
	const w = Math.max(1, Math.ceil(opts.width));
	const h = Math.max(1, Math.ceil(opts.height));
	const scale = Math.min(opts.scale, MAX_SIDE / w, MAX_SIDE / h);
	const capped = scale < opts.scale;
	mkdirSync(dirname(opts.out), { recursive: true });
	rmSync(opts.out, { force: true });
	const profile = mkdtempSync(join(tmpdir(), "pi-canvas-chrome-"));
	const args = [
		"--headless=new",
		"--disable-gpu",
		"--hide-scrollbars",
		"--no-first-run",
		"--no-default-browser-check",
		"--mute-audio",
		"--remote-debugging-pipe",
		`--window-size=${w},${h}`,
		`--force-device-scale-factor=${scale}`,
		`--user-data-dir=${profile}`,
		opts.url,
	];
	const child = spawn(opts.chrome, args, { stdio: ["ignore", "ignore", "pipe", "pipe", "pipe"] });
	let stderr = "";
	child.stderr?.on("data", (d) => (stderr = (stderr + d).slice(-2000)));
	const exited = new Promise<void>((r) => child.once("exit", () => r()));
	const input = child.stdio[3] as Writable;
	const output = child.stdio[4] as Readable;
	const pending = new Map<number, { method: string; resolve: (v: any) => void; reject: (e: Error) => void }>();
	let failure: Error | undefined;
	const fail = (err: Error) => {
		failure ??= err;
		for (const p of pending.values()) p.reject(failure);
		pending.clear();
		child.kill("SIGKILL");
	};
	let buf = Buffer.alloc(0);
	output.on("data", (chunk: Buffer) => {
		buf = Buffer.concat([buf, chunk]);
		let i: number;
		while ((i = buf.indexOf(0)) !== -1) {
			let msg: any;
			try {
				msg = JSON.parse(buf.subarray(0, i).toString("utf8"));
			} catch {
				msg = {};
			}
			buf = buf.subarray(i + 1);
			const p = msg.id ? pending.get(msg.id) : undefined;
			if (!p) continue;
			pending.delete(msg.id);
			if (msg.error) p.reject(new Error(`${p.method}: ${msg.error.message ?? "CDP error"}`));
			else p.resolve(msg.result ?? {});
		}
	});
	input.on("error", () => {});
	child.on("error", (err) => fail(new Error(`could not start ${opts.chrome}: ${err.message}`)));
	child.on("exit", (code) => fail(new Error(`headless Chrome exited early (code ${code})\n${stderr.trim().slice(-800)}`)));
	let seq = 0;
	const send = (method: string, params: object = {}, sessionId?: string): Promise<any> =>
		new Promise((resolve, reject) => {
			if (failure) return reject(failure);
			const id = ++seq;
			pending.set(id, { method, resolve, reject });
			input.write(`${JSON.stringify({ id, method, params, ...(sessionId ? { sessionId } : {}) })}\0`);
		});
	const timer = setTimeout(() => fail(new Error(`headless Chrome timed out after ${TIMEOUT_MS / 1000}s`)), TIMEOUT_MS);
	const onAbort = () => fail(new Error("screenshot aborted"));
	opts.signal?.addEventListener("abort", onAbort, { once: true });
	let complete = true;
	try {
		// attach to the tab Chrome opened for `url` and set the exact viewport; re-attach if the
		// initial renderer is swapped out while the page navigates
		const attach = async () => {
			let page: { targetId: string } | undefined;
			while (!page) {
				const { targetInfos } = await send("Target.getTargets");
				page = (targetInfos as { targetId: string; type: string }[]).find((t) => t.type === "page");
				if (!page) await new Promise((res) => setTimeout(res, 50));
			}
			const { sessionId } = await send("Target.attachToTarget", { targetId: page.targetId, flatten: true });
			await send("Emulation.setDeviceMetricsOverride", { width: w, height: h, deviceScaleFactor: scale, mobile: false }, sessionId);
			await send("Emulation.setDefaultBackgroundColorOverride", { color: { r: 0, g: 0, b: 0, a: 0 } }, sessionId);
			return sessionId as string;
		};
		let sessionId = await attach();
		const deadline = Date.now() + READY_MS;
		for (;;) {
			let v: unknown;
			try {
				v = (await send("Runtime.evaluate", { expression: READY_EXPR, returnByValue: true }, sessionId)).result?.value;
			} catch (err) {
				if (failure || !/session/i.test(String(err))) throw err;
				sessionId = await attach();
				continue;
			}
			if (v === "ok") break;
			if (v) throw new Error(`capture page: ${v}`);
			if (Date.now() > deadline) {
				complete = false;
				break;
			}
			await new Promise((res) => setTimeout(res, 100));
		}
		await new Promise((res) => setTimeout(res, SETTLE_MS));
		const shot = await send("Page.captureScreenshot", { format: "png" }, sessionId);
		const png = Buffer.from(shot.data, "base64");
		writeFileSync(opts.out, png);
		return { png, ...pngSize(png), scale, capped, complete };
	} finally {
		clearTimeout(timer);
		opts.signal?.removeEventListener("abort", onAbort);
		failure ??= new Error("closed");
		child.kill("SIGKILL");
		await Promise.race([exited, new Promise((r) => setTimeout(r, 2000))]);
		try {
			rmSync(profile, { recursive: true, force: true, maxRetries: 3 });
		} catch {
			// helper processes may still hold files; the OS temp dir is cleaned eventually
		}
	}
}
